/** Clave de la tabla de colores. */
export function clubColorKey(countryCode: string, name: string): string {
  return `${countryCode}:${name}`;
}

/** Colores reales (aproximados) de un club, o undefined si no hay entrada. */
export function clubColors(countryCode: string, name: string): readonly [string, string] | undefined {
  return CLUB_COLORS[clubColorKey(countryCode, name)];
}
